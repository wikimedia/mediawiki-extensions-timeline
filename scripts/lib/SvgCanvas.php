<?php

namespace MediaWiki\Extension\Timeline\Render;

/**
 * SVG output, as written by the ploticus SVG driver (svg.c by B. Traill).
 */
final class SvgCanvas extends Canvas {
	private const DPI = 72;
	private const DEF_FILL = 'fill:#000000;';
	private const DEF_STROKE = 'stroke:#000000;';
	private const DEF_FONT = '&ff;Helvetica;';

	private string $out = '';
	/** Offset of the provisional viewBox, which finish() overwrites */
	private int $viewBoxOffset = 0;
	private float $height = 0.0;

	// A moveTo is only written when a line or path starts from it.
	private float $moveX = 0.0;
	private float $moveY = 0.0;
	private bool $moved = false;
	private bool $lineInProgress = false;
	private bool $pathInProgress = false;
	private float $lastX = 0.0;
	private float $lastY = 0.0;

	private string $curColor = '#000000';
	private float $curLineWidth = 1.0;
	private string $fontName = 'Helvetica';
	private int $pointSize = 10;
	private string $align = 'start';
	private string $style = '';
	private bool $styleInProgress = false;

	public function begin( float $width, float $height ): void {
		$this->height = $height * self::DPI;
		$o = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\"?>\n"
			. "<!DOCTYPE svg PUBLIC \"-//W3C//DTD SVG 20010904//EN\" \n"
			. "  \"http://www.w3.org/TR/2001/REC-SVG-20010904/DTD/svg10.dtd\" [ \n";
		if ( $this->clickmap ) {
			$o .= "     <!ATTLIST svg \n        xmlns:a3 CDATA #IMPLIED \n"
				. "        a3:scriptImplementation CDATA #IMPLIED> \n"
				. "     <!ATTLIST script \n         a3:scriptImplementation CDATA #IMPLIED> \n";
		}
		$o .= "<!ENTITY ff \"font-family:\">\n<!ENTITY fs \"font-size:\">\n<!ENTITY fw \"font-weight:\">\n"
			. "<!ENTITY fst \"font-style:\">\n<!ENTITY sw \"stroke-width:\">\n<!ENTITY as \"text-anchor:start;\">\n"
			. "<!ENTITY am \"text-anchor:middle;\">\n<!ENTITY ae \"text-anchor:end;\">\n]>\n"
			. "<!-- Generated by ploticus (http://ploticus.sourceforge.net/)\nTitle: ploticus-graphic\n"
			. "SVG Driver by B.Traill\n-->\n"
			. "<svg xmlns=\"http://www.w3.org/2000/svg\" \n";
		$this->viewBoxOffset = strlen( $o );
		$o .= sprintf( "  viewBox=\"0 0  %-5.2f %-5.2f\" \n", $width * self::DPI, $this->height )
			. "  xmlns:xlink=\"http://www.w3.org/1999/xlink\"\n"
			. $this->scriptHeader( " > \n" )
			// Room for the final transform; the typo is in the original.
			. "<g tranform=\"translate(0,0)\"" . str_repeat( ' ', 71 ) . "\n\n"
			. '<g style="' . self::DEF_FILL . self::DEF_STROKE . self::DEF_FONT . "\">\n";
		$this->out = $o;
	}

	public function moveTo( float $x, float $y ): void {
		$this->endLine();
		$this->moveX = $x;
		$this->moveY = $y;
		$this->moved = true;
	}

	public function lineTo( float $x, float $y ): void {
		if ( $this->moved ) {
			$this->point( 'M', 'm', $this->moveX, $this->moveY );
		}
		$this->point( 'L', 'l', $x, $y );
		$this->moved = false;
		$this->lineInProgress = true;
	}

	public function pathTo( float $x, float $y ): void {
		$this->endLine();
		if ( $this->moved ) {
			$this->point( 'M', 'm', $this->moveX, $this->moveY );
		}
		$this->point( 'L', 'l', $x, $y );
		$this->moved = false;
	}

	public function fill(): void {
		$this->endLine();
		if ( $this->pathInProgress ) {
			$this->out .= "z\" fill=\"{$this->curColor}\" stroke=\"{$this->curColor}\"/>\n";
		}
		$this->pathInProgress = false;
	}

	public function endLine(): void {
		if ( $this->lineInProgress ) {
			if ( $this->pathInProgress ) {
				$this->out .= "\" fill=\"none\"/>\n";
			}
			$this->pathInProgress = false;
		}
		$this->lineInProgress = false;
	}

	public function text( string $align, string $s ): void {
		$this->endLine();
		$x = $this->moveX * self::DPI;
		$y = $this->height - ( $this->moveY * self::DPI );
		$this->align = match ( $align ) {
			'T' => 'start',
			'C' => 'middle',
			default => 'end',
		};
		$esc = preg_replace_callback( '/[<>]|&(?!#(?:x|\d))/', static fn ( $m ) => match ( $m[0] ) {
			'<' => '&lt;',
			'>' => '&gt;',
			default => '&amp;',
		}, $s );
		$this->printStyle();
		$this->out .= '<text x="' . Printf::f( $x, '.2' ) . '" y="' . Printf::f( $y, '.2' )
			. "\" stroke=\"none\">$esc</text>\n";
	}

	public function color( string $color ): string {
		$this->endLine();
		$color = strtolower( strtr( $color, '(),/:|-', '       ' ) );
		if ( str_starts_with( $color, 'rgb' ) ) {
			$rgb = self::scan( $color, 3 );
		} elseif ( str_starts_with( $color, 'gray' ) || str_starts_with( $color, 'grey' ) ) {
			$rgb = self::scan( $color, 1 );
			$rgb = $rgb ? [ $rgb[0], $rgb[0], $rgb[0] ] : null;
		} elseif ( str_starts_with( $color, 'xrgb' ) ) {
			$rgb = self::xrgb( substr( $color, 5 ) );
		} elseif ( str_starts_with( $color, 'x' ) ) {
			$this->curColor = '#' . substr( $color, 1 );
			return $color;
		} elseif ( self::isNumber( $color ) ) {
			// sscanf( "%f" ) reads a C float
			$g = self::trunc( self::f32( self::f32( self::atof( $color ) ) * 255 ) );
			$this->curColor = sprintf( '#%02x%02x%02x', $g, $g, $g );
			return $color;
		} else {
			$rgb = self::namedColor( $color );
		}
		if ( $rgb !== null ) {
			$this->curColor = vsprintf( '#%02x%02x%02x',
				array_map( static fn ( $c ) => self::trunc( $c * 255 ), $rgb ) );
		}
		return $color;
	}

	public function textSize( int $points ): void {
		$this->endLine();
		$this->pointSize = $points;
	}

	public function font( string $font ): void {
		$this->endLine();
		$this->fontName = str_starts_with( $font, '/' ) ? substr( $font, 1 ) : $font;
	}

	public function lineWidth( float $width ): void {
		$this->endLine();
		$this->curLineWidth = $width;
	}

	public function mapPoint( float $x, float $y ): array {
		return [ self::trunc( $x * 100 ), self::trunc( $y * 100 ) ];
	}

	/**
	 * Close the document and write the final viewBox over the provisional one.
	 */
	public function finish( float $x1, float $y1, float $x2, float $y2, array $regions ): void {
		$this->endLine();
		[ $x1, $y1, $x2, $y2 ] = [ $x1 - 0.05, $y1 - 0.05, $x2 + 0.05, $y2 + 0.05 ];
		if ( $this->styleInProgress ) {
			$this->out .= '</g>';
		}
		$this->out .= "</g>\n";
		if ( $this->clickmap ) {
			$this->out .= "<g style=\"fill-opacity:0;fill:red;\">\n";
			foreach ( $regions as [ $url, $label, $rx1, $ry1, $rx2, $ry2 ] ) {
				$this->linkRegion( $url, $label, $rx1, $ry1, $rx2, $ry2 );
			}
			$this->out .= "</g>\n";
		}
		$this->out .= "</g>\n</svg>\n";
		$p = self::DPI;
		$head = '  viewBox="0 0 ' . Printf::f( ( $x2 - $x1 ) * $p, '-5.2' ) . ' '
			. Printf::f( ( $y2 - $y1 ) * $p, '-5.2' )
			. "\"      \n  xmlns:xlink=\"http://www.w3.org/1999/xlink\"\n"
			. $this->scriptHeader( ">\n" )
			. '<g transform="translate(' . Printf::f( $x1 * $p * -1.0, '-5.2' ) . ','
			. Printf::f( ( $this->height - ( $y2 * $p ) ) * -1.0, '-5.2' ) . ')" >';
		// Written over the provisional header without truncating it
		$this->out = substr_replace( $this->out, $head, $this->viewBoxOffset, strlen( $head ) );
	}

	public function result(): string {
		return $this->out;
	}

	private function scriptHeader( string $plain ): string {
		if ( !$this->clickmap ) {
			return $plain;
		}
		return "  onload=\"init(evt)\"\n"
			. "  xmlns:a3=\"http://ns.adobe.com/AdobeSVGViewerExtensions/3.0/\" \n"
			. "  a3:scriptImplementation=\"Adobe\" >\n"
			. "<script type=\"text/ecmascript\" a3:scriptImplementation=\"Adobe\" xlink:href=\"ViewBox.js\"/> \n"
			. "<script type=\"text/ecmascript\" a3:scriptImplementation=\"Adobe\" xlink:href=\"GraphPopups.js\"/> \n";
	}

	private function printStyle(): void {
		$font = '&ff;' . $this->fontName . ';';
		$fill = "fill:{$this->curColor};";
		$stroke = "stroke:{$this->curColor};";
		$align = match ( $this->align ) {
			'start' => '&as;',
			'middle' => '&am;',
			'end' => '&ae;',
		};
		$new = sprintf( 'style="%s%s%s&sw;%3.1f;&fs;%dpt;%s"', $fill === self::DEF_FILL ? '' : $fill,
			$stroke === self::DEF_STROKE ? '' : $stroke, $font === self::DEF_FONT ? '' : $font,
			$this->curLineWidth, $this->pointSize, $align );
		if ( $new !== $this->style ) {
			if ( $this->styleInProgress ) {
				$this->out .= '</g>';
			}
			$this->out .= "<g $new>\n";
			$this->style = $new;
			$this->styleInProgress = true;
		}
	}

	private function point( string $abs, string $rel, float $x, float $y ): void {
		$x = $x * self::DPI;
		$y = $this->height - ( $y * self::DPI );
		if ( !$this->pathInProgress ) {
			$this->printStyle();
			$this->out .= '<path d="' . $abs . Printf::g( $x, 4 ) . ' ' . Printf::g( $y, 4 );
			$this->pathInProgress = true;
		} else {
			$this->out .= $rel . Printf::g( $x - $this->lastX, 4 ) . ' ' . Printf::g( $y - $this->lastY, 4 );
		}
		$this->lastX = $x;
		$this->lastY = $y;
	}

	private function linkRegion( string $url, string $label, int $x1, int $y1, int $x2, int $y2 ): void {
		[ $url, $target ] = self::splitTarget( $url );
		$p = self::DPI;
		$xx1 = ( $x1 / 100.0 ) * $p;
		$yy1 = $this->height - ( $y1 / 100.0 ) * $p;
		$xx2 = ( $x2 / 100.0 ) * $p;
		$yy2 = $this->height - ( $y2 / 100.0 ) * $p;
		if ( $url !== '' ) {
			$url = str_replace( [ '&', '<', '>' ], [ '&amp;', '&lt;', '&gt;' ], $url );
			$this->out .= "<a $target xlink:href=\"$url\">\n";
		}
		$this->out .= '<rect x="' . Printf::g( $xx1, 4 ) . '" y="' . Printf::g( $yy1, 4 )
			. '" width="' . Printf::g( $xx2 - $xx1, 4 )
			. '" height="' . Printf::g( abs( $yy2 - $yy1 ), 4 ) . '" ';
		if ( $label !== '' ) {
			$this->out .= "onmouseover='DisplayInfo(evt, \""
				. str_replace( [ '&', '<', '>', '"', "'" ], [ '&amp;', '&lt;', '&gt;', '&quot;', ' ' ], $label )
				. "\" )' onmouseout='RemoveInfo ();'";
		}
		$this->out .= " />\n";
		if ( $url !== '' ) {
			$this->out .= "</a>\n";
		}
	}

	/**
	 * sscanf( color, "%*s %lf %lf %lf" )
	 *
	 * @return float[]|null
	 */
	private static function scan( string $color, int $n ): ?array {
		$t = self::tokens( $color );
		$out = [];
		for ( $i = 1; $i <= $n; $i++ ) {
			$v = self::scanFloat( $t[$i] ?? '' );
			if ( $v === null ) {
				return null;
			}
			$out[] = $v;
		}
		return $out;
	}

	/**
	 * Round to C float precision.
	 */
	private static function f32( float $x ): float {
		return unpack( 'g', pack( 'g', $x ) )[1];
	}
}
